function localizzaGaraCalendario(gara, lingua) {
  const nome = NOMI_GP_2026[lingua]?.[gara.round - 1];
  if (!nome) {
    throw new Error(`Traduzione calendario mancante: ${lingua}, round ${gara.round}`);
  }
  return { ...gara, nome };
}

function localizzaCalendario(calendario, lingua = "it") {
  return {
    lingua,
    stagione: calendario.stagione,
    prossimi: calendario.prossimi.map((gara) =>
      localizzaGaraCalendario(gara, lingua),
    ),
    passati: calendario.passati.map((gara) =>
      localizzaGaraCalendario(gara, lingua),
    ),
  };
}

